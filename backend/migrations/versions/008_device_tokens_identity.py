"""fix device_tokens id generation

El modelo declara ``device_tokens.id`` como ``Integer`` con ``Identity``, pero en
producción la columna quedó con otro tipo (p. ej. ``uuid`` en Supabase) y sin
valor por defecto. Por eso:

1. El ``INSERT`` del ORM —que omite ``id``— fallaba con ``NotNullViolation``.
2. ``ALTER COLUMN id ADD GENERATED ... AS IDENTITY`` falla con
   ``InvalidParameterValue: identity column type must be smallint, integer, or bigint``
   porque IDENTITY solo aplica a tipos enteros.

Esta migración inspecciona el tipo real y alinea la columna con el modelo,
conservando las filas y sin crear secuencias ni valores duplicados:

- Si ``id`` ya genera valores (default o identity), no hace nada.
- Si ``id`` es entero, agrega la identidad que falte.
- Si ``id`` es de otro tipo (``uuid``, ``text``, ``numeric``...), lo convierte a
  ``integer`` asignando ids únicos con una secuencia temporal.

Revision ID: 008_device_tokens_identity
Revises: 007_add_device_tokens
"""

from alembic import op

# revision identifiers, used by Alembic.
revision = "008_device_tokens_identity"
down_revision = "007_add_device_tokens"
branch_labels = None
depends_on = None

# Idempotente y consciente del tipo. Todo el bloque es una sola sentencia, así
# que se comporta igual en ejecución online y en ``alembic ... --sql``.
_UPGRADE_SQL = """
DO $$
DECLARE
    v_data_type     text;
    v_has_default   boolean;
    v_is_identity   text;
BEGIN
    SELECT data_type,
           (column_default IS NOT NULL),
           is_identity
      INTO v_data_type, v_has_default, v_is_identity
      FROM information_schema.columns
     WHERE table_schema = 'public'
       AND table_name = 'device_tokens'
       AND column_name = 'id';

    IF v_data_type IS NULL THEN
        RAISE NOTICE 'device_tokens.id no existe; nada que corregir';
        RETURN;
    END IF;

    -- Ya genera valores: no tocar para no duplicar secuencias/identidades.
    IF v_has_default OR v_is_identity = 'YES' THEN
        RAISE NOTICE 'device_tokens.id ya genera valores (%); sin cambios', v_data_type;
        RETURN;
    END IF;

    IF v_data_type IN ('smallint', 'integer', 'bigint') THEN
        ALTER TABLE device_tokens
            ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;
        PERFORM setval(
            pg_get_serial_sequence('device_tokens', 'id'),
            COALESCE((SELECT MAX(id) FROM device_tokens), 0) + 1,
            false
        );
        RAISE NOTICE 'device_tokens.id (%) ahora usa identity', v_data_type;
    ELSE
        -- Tipo incompatible (uuid, text, ...). Se convierte a integer con una
        -- secuencia temporal: se conservan las filas y cada una recibe un id
        -- único y nuevo, sin reutilizar valores ni chocar con el NOT NULL.
        CREATE SEQUENCE IF NOT EXISTS device_tokens_id_tmp_seq;
        ALTER TABLE device_tokens
            ALTER COLUMN id TYPE integer
            USING (nextval('device_tokens_id_tmp_seq')::integer);
        DROP SEQUENCE IF EXISTS device_tokens_id_tmp_seq;
        ALTER TABLE device_tokens
            ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;
        PERFORM setval(
            pg_get_serial_sequence('device_tokens', 'id'),
            COALESCE((SELECT MAX(id) FROM device_tokens), 0) + 1,
            false
        );
        RAISE NOTICE 'device_tokens.id (%) convertido a integer con identity', v_data_type;
    END IF;
END $$;
"""


def upgrade() -> None:
    op.execute(_UPGRADE_SQL)


def downgrade() -> None:
    op.execute("ALTER TABLE device_tokens ALTER COLUMN id DROP IDENTITY IF EXISTS")
